#!/usr/bin/env python3
"""
Move data and links from the aec_* modules to the adiro_* modules that replace them (#171).

The adiro_* modules are the aec_* modules under new names: their terms, definitions and axioms are those of the aec_* final
releases, so moving is a change of IRIs, nothing else. Every rename is listed in config/module_renames.json.

    mapping [--out FILE]   write the published mapping: one `<old> dcterms:isReplacedBy <new>` per term and per ontology of
                           the final aec_* releases (default: migration/aec_to_adiro.ttl)
    rewrite IN [OUT]       rewrite an RDF file (Turtle, N-Triples, RDF/XML, JSON-LD, TriG, N-Quads: by its extension) to the
                           new IRIs; OUT defaults to IN with ".adiro" before the extension
    links IN [OUT]         rewrite every old IRI in any text file (a list of links, a JSON or CSV export, code), leaving the
                           rest of the text as it is

What changes: a module's ontology IRI (`…/aec_x` -> `…/adiro_x`), the IRI of every term it defines (`…/aec_x#Term` ->
`…/adiro_x#Term`) and the addresses of its example images (`…/aec_x/exampleImage/…`). What does not: a version IRI of an old
release (`…/aec_x/1.0.0`), which keeps naming that release, and every IRI outside ADIRO.

Data written against an aec_* release older than the final one may also use terms that the final release moved or removed
(see the changelogs); those are not rewritten here.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import module_renames as mr  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MAPPING = Path("migration") / "aec_to_adiro.ttl"
FORMATS = {".ttl": "turtle", ".nt": "nt", ".rdf": "xml", ".owl": "xml", ".xml": "xml", ".jsonld": "json-ld",
           ".json": "json-ld", ".trig": "trig", ".nq": "nquads", ".n3": "n3"}
DATASET_FORMATS = {"trig", "nquads", "json-ld"}  # the formats that can carry named graphs


def final_release(root, module):
    """The snapshot of the module's last release, or None."""
    import compat_diff

    return compat_diff.latest_snapshot(root, module)


def mapping_pairs(root=ROOT):
    """(old IRI, new IRI), sorted: each renamed module's ontology and every term its final release defines."""
    from rdflib import Graph, URIRef

    renames = mr.load(root)
    pairs = set()
    for new, old in sorted(renames.items()):
        snapshot = final_release(root, old)
        if snapshot is None:
            continue
        graph = Graph().parse(str(snapshot), format="turtle")
        base = mr.BASE + old
        for term in set(graph.subjects()) | set(graph.objects()):
            if isinstance(term, URIRef) and (str(term) == base or str(term).startswith(base + "#")):
                pairs.add((str(term), mr.rename_iri(str(term), renames)))
    return sorted(pairs)


def mapping_turtle(root=ROOT):
    lines = [
        "# The IRIs of the aec_* modules and the adiro_* IRIs that replace them (#171), one statement per ontology and term.",
        "# Generated by scripts/migrate_aec_to_adiro.py mapping, from the final release of each aec_* module.",
        "@prefix dcterms: <http://purl.org/dc/terms/> .",
        "",
    ]
    lines += [f"<{old}> dcterms:isReplacedBy <{new}> ." for old, new in mapping_pairs(root)]
    return "\n".join(lines) + "\n"


def rewrite_graph_file(source, target, root=ROOT):
    """Parse an RDF file, map every IRI of a renamed module to its new name, and write it in the same format.

    A format that can carry named graphs (TriG, N-Quads, JSON-LD) is read as a dataset: the default graph and every named
    graph are rewritten, and so is a graph name that is an old IRI. Reading JSON-LD as a single graph would silently drop
    the triples of its named graphs (#210 review).
    """
    from rdflib import Dataset, Graph, URIRef
    from rdflib.graph import DATASET_DEFAULT_GRAPH_ID

    fmt = FORMATS.get(Path(source).suffix.lower())
    if fmt is None:
        raise SystemExit(f"{source}: unknown RDF format; use `links` to rewrite it as text")
    renames = mr.load(root)
    if fmt in DATASET_FORMATS:
        data, out = Dataset(), Dataset()
        data.parse(str(source), format=fmt)
        for prefix, namespace in data.namespaces():
            out.bind(prefix, mr.rewrite_text(str(namespace), renames), override=True, replace=True)
        for graph in data.graphs():
            name = graph.identifier
            if name == DATASET_DEFAULT_GRAPH_ID:
                target_graph = getattr(out, "default_graph", None) or out.default_context  # rdflib 7 renamed it
            else:
                target_graph = out.graph(URIRef(mr.rename_iri(str(name), renames)) if isinstance(name, URIRef) else name)
            for triple in mr.rewrite_graph(graph, renames):
                target_graph.add(triple)
    else:
        out = mr.rewrite_graph(Graph().parse(str(source), format=fmt), renames)
    Path(target).write_text(out.serialize(format=fmt), encoding="utf-8")


def rewrite_text(text, root=ROOT):
    """The text with every old ontology, term and image address of a renamed module replaced; version IRIs are kept."""
    return mr.rewrite_text(text, mr.load(root))


def default_target(source):
    source = Path(source)
    return source.with_name(f"{source.stem}.adiro{source.suffix}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_map = sub.add_parser("mapping")
    p_map.add_argument("--out", default=str(ROOT / MAPPING))
    for name in ("rewrite", "links"):
        p = sub.add_parser(name)
        p.add_argument("source")
        p.add_argument("target", nargs="?")
    args = ap.parse_args(argv)
    if args.cmd == "mapping":
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(mapping_turtle(), encoding="utf-8")
        print(f"wrote {args.out}")
        return
    target = args.target or default_target(args.source)
    if args.cmd == "rewrite":
        rewrite_graph_file(args.source, target)
    else:
        Path(target).write_text(rewrite_text(Path(args.source).read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
